#!/usr/bin/env python3
# The BC decoder's tables (../bc_decode.c) and the ETC / EAC tables (../etc_encode.c) as GLSL constants for bc_gpu.comp: read from the C sources, so the GPU
# and CPU paths can never use different tables. Output: bc_gpu_tables.glsl (run by build_spv.sh)
import re, os
H = os.path.dirname(os.path.abspath(__file__)); dec = open(os.path.join(H, '../bc_decode.c')).read(); enc = open(os.path.join(H, '../etc_encode.c')).read()
def arr(src, name):
    m = re.search(r'%s\s*\[[^\]]*\](?:\[[^\]]*\])?\s*=\s*\{(.*?)\};' % re.escape(name), src, re.S)
    return [int(x, 0) for x in re.findall(r'-?0x[0-9A-Fa-f]+|-?\d+', m.group(1))]
part2 = arr(dec, 'part2'); part3 = arr(dec, 'part3'); a2 = arr(dec, 'anchor2'); a3a = arr(dec, 'anchor3a'); a3b = arr(dec, 'anchor3b')
assert len(part2) == 64 and len(part3) == 64 * 16 and len(a2) == len(a3a) == len(a3b) == 64
p3 = [sum(part3[i * 16 + t] << (2 * t) for t in range(16)) for i in range(64)]
# BC6H mode layouts: fields (endpoint value, first bit, count) per mode 1..14, flat, with each mode's start
lay = {}
for m in re.finditer(r'static const fld (L\d+)\[\] = \{(.*?)\{255,0,0\} \};', dec): lay[m.group(1)] = [tuple(int(v) for v in f) for f in re.findall(r'F\((\d+),(\d+),(-?\d+)\)', m.group(2))]
modes = re.search(r'BC6M\[15\] = \{(.*?)\};', dec, re.S).group(1)
rows = re.findall(r'\{(L\d+), (\d+), (\d+), (\d+), \{(\d+), (\d+), (\d+)\}\}', modes); assert len(rows) == 14
flat, start = [], []
for r in rows: start.append(len(flat)); flat += [v | lo << 8 | (n & 0xff) << 16 for v, lo, n in lay[r[0]]]
start.append(len(flat))
info = [int(r[1]) | int(r[2]) << 4 | int(r[3]) << 8 | int(r[4]) << 16 | int(r[5]) << 20 | int(r[6]) << 24 for r in rows]   # regions, xf, eb, db r g b
etc = arr(enc, 'ETC_TAB'); eac = arr(enc, 'EAC_TAB'); assert len(etc) == 16 and len(eac) == 128
# ASTC's trit encoding (etc_encode.c trit_init, the inverse of the specification's trit-block decode: the smallest code wins)
trit = [0] * 243
for T in range(255, -1, -1):
    t = [0] * 5
    if ((T >> 2) & 7) == 7: C = ((T >> 5) & 7) << 2 | (T & 3); t[4] = t[3] = 2
    else:
        C = T & 31
        if ((T >> 5) & 3) == 3: t[4] = 2; t[3] = T >> 7 & 1
        else: t[4] = T >> 7 & 1; t[3] = T >> 5 & 3
    if (C & 3) == 3: t[2] = 2; t[1] = C >> 4 & 1; t[0] = (C >> 3 & 1) << 1 | ((C >> 2 & 1) & ~(C >> 3) & 1)
    elif ((C >> 2) & 3) == 3: t[2] = 2; t[1] = 2; t[0] = C & 3
    else: t[2] = C >> 4 & 1; t[1] = C >> 2 & 3; t[0] = (C >> 1 & 1) << 1 | ((C & 1) & ~(C >> 1) & 1)
    trit[t[0] + 3 * t[1] + 9 * t[2] + 27 * t[3] + 81 * t[4]] = T
def g(t, n, v): return 'const %s %s[%d] = %s[](%s);\n' % (t, n, len(v), t, ','.join(('%du' % x if t == 'uint' else '%d' % x) for x in v))
out = '// Generated by gen_tables.py from ../bc_decode.c and ../etc_encode.c: do not edit\n'
out += g('uint', 'PART2', part2) + g('uint', 'PART3', p3) + g('uint', 'ANCHOR2', a2) + g('uint', 'ANCHOR3A', a3a) + g('uint', 'ANCHOR3B', a3b)
out += g('uint', 'BC6F', flat) + g('uint', 'BC6START', start) + g('uint', 'BC6INFO', info) + g('int', 'ETC_TAB', etc) + g('int', 'EAC_TAB', eac) + g('uint', 'TRIT_ENC', trit)
open(os.path.join(H, 'bc_gpu_tables.glsl'), 'w', newline='\n').write(out); print('tables:', len(flat), 'BC6H fields')
