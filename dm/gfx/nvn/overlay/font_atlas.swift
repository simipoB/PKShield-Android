// Renders the overlay's button labels (A B X Y L R ZL ZR + −) into a 16-cell R8 atlas of 64x64 cells and writes ovl_font.h (nvn_vk.c ovl_*). Run: swift font_atlas.swift
import CoreGraphics
import CoreText
import Foundation
let labels = ["A", "B", "X", "Y", "L", "R", "ZL", "ZR", "+", "\u{2212}"]
let cell = 64, cells = 16, W = cell * cells, H = cell
var px = [UInt8](repeating: 0, count: W * H)
let cs = CGColorSpaceCreateDeviceGray()
let ctx = CGContext(data: &px, width: W, height: H, bitsPerComponent: 8, bytesPerRow: W, space: cs, bitmapInfo: CGImageAlphaInfo.none.rawValue)!
ctx.setFillColor(gray: 1, alpha: 1)
for (i, s) in labels.enumerated() {
    let size: CGFloat = s.count > 1 ? 30 : 46
    let font = CTFontCreateWithName("Helvetica-Bold" as CFString, size, nil)
    let attr = NSAttributedString(string: s, attributes: [NSAttributedString.Key(kCTFontAttributeName as String): font, NSAttributedString.Key(kCTForegroundColorFromContextAttributeName as String): true])
    let line = CTLineCreateWithAttributedString(attr)
    let b = CTLineGetBoundsWithOptions(line, .useGlyphPathBounds)
    ctx.textPosition = CGPoint(x: CGFloat(i * cell) + (CGFloat(cell) - b.width) / 2 - b.minX, y: (CGFloat(cell) - b.height) / 2 - b.minY)
    CTLineDraw(line, ctx)
}
var out = "// Generated by font_atlas.swift: the touch overlay's labels, \(cells) cells of \(cell)x\(cell), R8, top row first\nstatic const unsigned ovl_font_w = \(W), ovl_font_h = \(H);\nstatic const unsigned char ovl_font[] = {\n"
for y in 0..<H { out += (0..<W).map { String(px[y * W + $0]) }.joined(separator: ",") + ",\n" }
out += "};\n"
try! out.write(toFile: "ovl_font.h", atomically: true, encoding: .utf8)
print("ovl_font.h: \(W)x\(H)")
