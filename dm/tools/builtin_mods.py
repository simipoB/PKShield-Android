#!/usr/bin/env python3
# Built-in code mods: community IPSwitch .pchtxt patches the app ships as settings (dm/games/<title>/builtin_mods/<name>.pchtxt), turned into the table loader.c applies
#   (dm/host/builtin_mods.h). Each site keeps the bytes the game has there, read from the game's own decompressed main, so the loader applies a mod only to a main whose
#   every site still holds them: all of a mod or none of it.
# Usage: builtin_mods.py <main image> <out .h> <name>=<pchtxt>[,<extra build id>...] ...
#   <main image>: the main module decompressed (offset 0 = the module's base, as the setup's main.img); the extra build IDs are other mains with the same code at every
#   site (Violet 4.0.0's main for Scarlet's mods: the two games are one engine build, compared site by site)
import re, sys

def parse(path):
    bid, shift, en, sites = None, 0, False, []
    for ln in open(path, encoding='utf-8', errors='replace'):
        t = re.split(r'//|#', ln)[0].strip()
        if not t: continue
        if t.startswith('@'):
            m = re.match(r'@nsobid-([0-9A-Fa-f]+)', t)
            if m: bid = m.group(1)[:32].lower()
            m = re.match(r'@flag\s+offset_shift\s+(\S+)', t)
            if m: shift = int(m.group(1), 0)
            if t.lower() == '@enabled': en = True
            elif t.lower() == '@disabled': en = False
            elif t.lower() == '@stop': break
            continue
        if not en: continue
        a, v = t.split(None, 1)
        sites.append((int(a, 16) + shift - 0x100, bytes.fromhex(v.replace(' ', ''))))
    return bid, sites

def main():
    img = open(sys.argv[1], 'rb').read(); out = sys.argv[2]
    lines = ['// Generated by dm/tools/builtin_mods.py from dm/games/*/builtin_mods/*.pchtxt: do not edit. Each site: offset in main, length, the game\'s bytes, the mod\'s bytes',
             '#pragma once', '#include <stdint.h>',
             'typedef struct { uint32_t off, len; const uint8_t *orig, *mod; } bmod_site;',
             'typedef struct { const char *name; const char *builds[4]; const bmod_site *sites; int n; } bmod;', '']
    mods = []
    for arg in sys.argv[3:]:
        name, rest = arg.split('=', 1); path, *extra = rest.split(',')
        bid, sites = parse(path)
        rows = []
        for i, (off, b) in enumerate(sites):
            o = img[off:off + len(b)]
            if len(o) != len(b): sys.exit(f'{name}: site {off:#x} is outside the image')
            hx = lambda x: ', '.join(f'0x{c:02x}' for c in x)
            lines.append(f'static const uint8_t bm_{name}_{i}_o[] = {{ {hx(o)} }}, bm_{name}_{i}_m[] = {{ {hx(b)} }};')
            rows.append(f'    {{ {off:#x}, {len(b)}, bm_{name}_{i}_o, bm_{name}_{i}_m }},')
        lines += [f'static const bmod_site bm_{name}[] = {{'] + rows + ['};', '']
        builds = ', '.join(f'"{b}"' for b in [bid] + [e.lower()[:32] for e in extra]) + ', NULL'
        mods.append(f'    {{ "{name}", {{ {builds} }}, bm_{name}, {len(sites)} }},')
        print(f'{name}: {len(sites)} sites from {path}')
    lines += ['static const bmod BUILTIN_MODS[] = {'] + mods + ['};', '']
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))

if __name__ == '__main__': main()
