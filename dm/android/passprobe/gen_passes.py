#!/usr/bin/env python3
# Turns an engine log with pass logging (DM_VK_LOG_PASSES, the [pass] / [pass-att] lines) into passes.h for the pass replay probe:
# the game's render targets (image and view parameters) and its passes, frame by frame, in order. No game data: sizes, formats and order only.
# Usage: gen_passes.py <log.txt> <passes.h> [max frame (default 12)]
import re, sys

log, out = sys.argv[1], sys.argv[2]
maxf = int(sys.argv[3]) if len(sys.argv) > 3 else 12
imgs, img_ix, views, view_ix, passes = [], {}, [], {}, []
pend = []   # [pass-att] lines of the pass being begun (logged before its [pass] line)
kv = lambda s, k: re.search(r'\b' + k + r' (\S+)', s).group(1)

def img_of(s):
    w, h, d = map(int, kv(s, 'image').split('x'))
    key = (kv(s, 'img'), w, h, d, int(kv(s, 'fmt')), int(kv(s, 'levels')), int(kv(s, 'layers')), int(kv(s, 'samples')), int(kv(s, 'usage'), 16),
           int(re.search(r'\b3d (\d+)', s).group(1)) if ' 3d ' in s else 0, int(kv(s, 'cube')) if ' cube ' in s else 0)
    if key not in img_ix: img_ix[key] = len(imgs); imgs.append(key)
    return img_ix[key]

def view_of(s, depth):
    i = img_of(s)
    vf = int(kv(s, 'fmt')) if depth else int(re.search(r'view fmt (\d+)', s).group(1))
    bl = int(re.search(r'view base level (-?\d+)', s).group(1)); bly = int(re.search(r' layer (-?\d+)', s.split('view base level')[1]).group(1))
    key = (i, vf, max(bl, 0), max(bly, 0), int(re.search(r'att layers (\d+)', s).group(1)))
    if key not in view_ix: view_ix[key] = len(views); views.append(key)
    return view_ix[key]

lines = open(log, encoding='utf-8', errors='replace').read().splitlines()
i = 0
while i < len(lines):
    s = lines[i]
    if '[pass-att]' in s: pend.append(s)
    elif '[pass] #' in s:
        fr = int(kv(s, 'frame'))
        cols = []
        j = i + 1
        while j < len(lines) and '[pass]   colour' in lines[j]:
            c = lines[j]; cols.append((int(kv(c, 'colour')), int(kv(c, 'load')), int(kv(c, 'layout')))); j += 1
        if fr <= maxf:
            w, h = map(int, kv(s, 'area').split(' ')[0].split('x')) if False else map(int, re.search(r'area \S+ (\d+x\d+)', s).group(1).split('x'))
            sc = int(kv(s, 'swapchain'))
            cv = [-1] * 8; cl = [0] * 8
            att_c = {int(kv(a, 'colour')): a for a in pend if '[pass-att] colour' in a}
            att_d = [a for a in pend if '[pass-att] depth' in a]
            for (ci, load, layout) in cols:
                cl[ci] = load
                cv[ci] = -2 if sc else (view_of(att_c[ci], 0) if ci in att_c else -3)
            hasd = kv(s, 'depth') not in ('0x0', '(nil)'); hass = kv(s, 'stencil') not in ('0x0', '(nil)')
            dv = view_of(att_d[0], 1) if (hasd or hass) and att_d else -1
            passes.append((fr, sc, w, h, int(kv(s, 'layers')), int(kv(s, 'colours')), cv, cl, dv, int(hasd), int(hass), int(kv(s, 'site'))))
        pend = []; i = j; continue
    i += 1

with open(out, 'w') as f:
    f.write('// Generated by gen_passes.py from %s: %d images, %d views, %d passes (frames 0-%d). Sizes, formats and order of the game\'s render targets only.\n' % (log.replace('\\', '/').split('/')[-1], len(imgs), len(views), len(passes), maxf))
    f.write('static const pp_img PP_IMGS[] = {\n')
    for (_, w, h, d, fmt, lv, ly, sm, us, is3d, cube) in imgs: f.write('    { %d, %d, %d, %d, %d, %d, %d, 0x%x, %d, %d },\n' % (w, h, d, fmt, lv, ly, sm, us, is3d, cube))
    f.write('};\nstatic const pp_view PP_VIEWS[] = {\n')
    for (im, vf, bl, bly, nl) in views: f.write('    { %d, %d, %d, %d, %d },\n' % (im, vf, bl, bly, nl))
    f.write('};\nstatic const pp_pass PP_PASSES[] = {\n')
    for (fr, sc, w, h, ly, nc, cv, cl, dv, hd, hs, site) in passes:
        f.write('    { %d, %d, %d, %d, %d, %d, { %s }, { %s }, %d, %d, %d, %d },\n' % (fr, sc, w, h, ly, nc, ', '.join(map(str, cv)), ', '.join(map(str, cl)), dv, hd, hs, site))
    f.write('};\n')
print('images', len(imgs), 'views', len(views), 'passes', len(passes), 'unknown colour views', sum(p[6].count(-3) for p in passes))
