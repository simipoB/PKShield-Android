#!/bin/bash
# The probe's self-test shaders → SPIR-V (Vulkan 1.1 / SPIR-V 1.3, the same target as the BC layer) → ../jni/selftest_spv.h, validated with spirv-val.
# GLSLC / SPIRV_VAL: the NDK's (default: $NDK/shader-tools/linux-x86_64, NDK=~/psa-build/android-ndk-r27c), else on PATH.
# floatctl.comp and shmath.comp are built without optimisation (-O0) so the NaN / infinity checks reach the driver as written.
set -e
O=$(cd "$(dirname "$0")" && pwd)
NDK=${NDK:-$HOME/psa-build/android-ndk-r27c}
ST=$NDK/shader-tools/linux-x86_64
GLSLC=${GLSLC:-$( [ -x "$ST/glslc" ] && echo "$ST/glslc" || echo glslc )}
SPIRV_VAL=${SPIRV_VAL:-$( [ -x "$ST/spirv-val" ] && echo "$ST/spirv-val" || echo spirv-val )}
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
for s in barrier reinterp; do "$GLSLC" -fshader-stage=compute --target-env=vulkan1.1 -O "$O/$s.comp" -o "$T/$s.spv"; done
for s in floatctl shmath; do "$GLSLC" -fshader-stage=compute --target-env=vulkan1.1 -O0 "$O/$s.comp" -o "$T/$s.spv"; done
"$GLSLC" -fshader-stage=vertex --target-env=vulkan1.1 -O "$O/fallback.vert" -o "$T/fallback_vert.spv"
"$GLSLC" -fshader-stage=fragment --target-env=vulkan1.1 -O "$O/fallback.frag" -o "$T/fallback_frag.spv"
for s in barrier reinterp floatctl shmath fallback_vert fallback_frag; do "$SPIRV_VAL" --target-env vulkan1.1 "$T/$s.spv"; done
(python3 - "$T" "$O/../jni/selftest_spv.h" 2>/dev/null || python - "$T" "$O/../jni/selftest_spv.h") <<'PY'
import struct, sys
t, out = sys.argv[1], sys.argv[2]
lines = ['// Generated by shaders/build_spv.sh (glslc, Vulkan 1.1): the probe self-tests\' compute shaders. Do not edit.', '#pragma once', '#include <stdint.h>']
for s in ('barrier', 'reinterp', 'floatctl', 'shmath', 'fallback_vert', 'fallback_frag'):
    b = open('%s/%s.spv' % (t, s), 'rb').read(); w = struct.unpack('<%dI' % (len(b) // 4), b)
    lines.append('static const uint32_t spv_%s[] = {%s};' % (s, ','.join(hex(x) for x in w)))
    print('%s: %d words' % (s, len(w)))
open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
PY
